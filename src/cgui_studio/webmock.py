def build_mock_tar(path: Path, jobid: str) -> Path:
    """Write to ``path`` a tar.gz test with the tree of a completed real Quick Bilayer."""
    path.parent.mkdir(parents=True, exist_ok=True)
    entries: dict[str, bytes] = {
        "system/step1_pdbreader.pdb": bilayer_pdb_bytes(),
        "system/step2.2_ions_count.str": _IONS_STR.encode("utf-8"),
        "system/step5_membrane/gromacs/topol.top": _TOPOL_TOP.encode("utf-8"),
        "README.txt": (
            "archivio FAKE generated by cgui-studio webmock (CGUI_MOCK=1):\n"
            "no build real CHARMM-GUI. jobid before download: ...\n"
            f"jobid: {jobid}\n"
            "files: pdb of fake bilayer (spacefill in GUI) + ions + topol topology.\n"
        ).encode(),
    }
    with tarfile.open(path, "w:gz") as tar:
        for name, blob in entries.items():
            info = tarfile.TarInfo(name=name)
            info.size = len(blob)
            tar.addfile(info, io.BytesIO(blob))
    return path


class FakeClient:
    """Ingestible client in webui.create_app(mock=True, client=...).

    Status timeline from the submit instant: < 3 s pending, 3-8 s
    running with step 2, > 8 s done with tar available. It uses a `clock`
    injectable (many tests advance the virtual clock with no sleep).
    """

    def __init__(
        self,
        *,
        clock: Callable[[], float] | None = None,
        sleep: Callable[[float], None] = time.sleep,
        seed: int | None = None,  # None = entropia del runtime: jobid sempre diversi
    ) -> None:
        self.clock = clock or time.monotonic
        self.sleep = sleep
        self._rng = random.Random(seed)  # seed None → entropia OS (niente collisioni jobid)
        self._t0: dict[str, float] = {}

    # ---------------------------------------------------------------- -- auth
    def token(self) -> str:
        return "mock-token-not-real"

    # ---------------------------------------------------------------- -- API
    def submit(self, spec: Spec) -> dict[str, object]:
        jobid = "".join(self._rng.choices("0123456789", k=10))
        self._t0[jobid] = self.clock()
        return {
            "submitted": "true",
            "modules": "membuilder,ffconverter",
            "jobid": jobid,
            "recipe": "mock",
        }

    def status(self, jobid: str) -> JobStatus:
        if jobid not in self._t0:
            raise JobError(f"job {jobid} unknown in mock server")
        elapsed = self.clock() - self._t0[jobid]
        if elapsed < 3.0:
            return JobStatus(jobid=jobid, status="pending", rank="3 job(s) ahead")
        if elapsed < 8.0:
            return JobStatus(jobid=jobid, status="running", last_inp_step=2)
        return JobStatus(jobid=jobid, status="done", has_tar=True)

    def wait(
        self,
        jobid: str,
        *,
        timeout_s: float = 3600,
        interval_s: float = 1.0,
        on_update: Callable[[JobStatus], None] | None = None,
    ) -> JobStatus:
        start = self.clock()
        while True:
            st = self.status(jobid)
            if on_update is not None:
                on_update(st)
            if st.status == "done":
                return st
            if st.status == "error":
                raise JobError(f"job {jobid} errore mock: {st.error}")
            if self.clock() - start > timeout_s:
                raise ApiError(f"timeout in mock: {timeout_s} s", 504)
            self.sleep(min(interval_s, max(0.01, timeout_s - (self.clock() - start))))

    def download(self, jobid: str, dest: Path) -> Path:
        if jobid not in self._t0:
            raise JobError(f"job {jobid} unknown in mock server")
        return build_mock_tar(Path(dest), jobid)
