_RES_SYMMETRIC_PATH_STEP = (16.0, 12.0, 8.0, 4.0)  # distance of the center of chain residue
_RESNAMES_STYLE = ("GLY", "OLE", "GLY", "OLE")


def _atom_line(
    serial: int, name: str, resname: str, resid: int, x: float, y: float, z: float, element: str
) -> str:
    return (
        f"ATOM  {serial:5d} {name:<4s} {resname:>3s} X{resid:4d}    "
        f"{x:8.3f}{y:8.3f}{z:8.3f}  1.00  0.00          {element:>2s}\n"
    )


def bilayer_pdb_bytes(
    *, lipids_side: int = 8, z_leaflet: float = 20.0, seed: int = 20261026
) -> bytes:
    """Fake all-atom bilayer: POPC-like lipids (head of 2 atoms + 4 chain residues,
    2 GLY + 2 OLE) on 2 leaflets, water (TIP3) and ions (SOD/POT/CLA).

    Deterministic grid with fixed seed (reproducible sha in every mock fetch).
    """
    rng = random.Random(seed)
    cols = rows = lipids_side
    span = cols * 8.0
    out: list[str] = [
        f"CRYST1  {span:8.3f}  {span:8.3f}   80.000  90.00  90.00  90.00  P 1           1\n"
    ]

    serial = 0
    resid = 0

    def add(name: str, resname: str, x: float, y: float, z: float, element: str) -> None:
        nonlocal serial
        serial += 1
        out.append(_atom_line(serial, name, resname, resid, x, y, z, element))

    for zsign in (1, -1):
        for i in range(cols):
            for j in range(rows):
                x = (i - cols / 2) * 8.0 + 4.0 + rng.uniform(-0.8, 0.8)
                y = (j - rows / 2) * 8.0 + 4.0 + rng.uniform(-0.8, 0.8)
                z0 = zsign * z_leaflet
                resid += 1
                # polar head: 2 atoms, names N / P, resname POP ("head sheet" z = ±20 Å)
                add("N", "POP", x + 1.0, y, z0, "N")
                add("P", "POP", x - 1.0, y + 0.6, z0 - zsign * 1.2, "P")
                for idx, resname in enumerate(_RESNAMES_STYLE):  # 4 chain residues GLY/OLE
                    resid += 1
                    zc = zsign * _RES_SYMMETRIC_PATH_STEP[idx]
                    for k in range(12):  # 12 atoms per chain residue -> ~10k atoms in total
                        add(
                            f"C{k + 1}",
                            resname,
                            x + rng.uniform(-1.4, 1.4),
                            y + rng.uniform(-1.4, 1.4),
                            zc + rng.uniform(-0.5, 0.5),
                            "C",
                        )
                # small oxygen in the head to enrich inter-leaflet contacts
                resid += 1
                add("O", "POP", x, y - 1.6, z0 + zsign * 1.0, "O")

    # water above and below the bilayer
    for _ in range(3500):
        x, y = rng.uniform(-span / 2, span / 2), rng.uniform(-span / 2, span / 2)
        z = rng.choice((1.0, -1.0)) * rng.uniform(24.0, 34.0)
        resid += 1
        add("O", "TIP", x, y, z, "O")

    # ions scattered in the solvent (SOD/POT/CLA: names hidden by the GUI)
    _count = 0
    for _ in range(40):
        _count += 1
        x, y = rng.uniform(-span / 2, span / 2), rng.uniform(-span / 2, span / 2)
        z = rng.choice((1.0, -1.0)) * rng.uniform(24.0, 32.0)
        resname = ("SOD", "POT", "CLA")[_count % 3]
        resid += 1
        add(resname, resname, x, y, z, "C" if resname == "CLA" else "N")

    out.append("END\n")
    return "".join(out).encode("ascii")


