"""Dummy client + generated fake bilayer, used when ``CGUI_MOCK=1``.

It does NOT touch the real ``Client``: same ``duck-typing`` interface
(``token/submit/status/wait/download``) for direct injection into
``webui.create_app``. The tar.gz contains a complete if plausible fake bilayer
(2 leaflets at z = ±2 nm + water/ions) so that the NGL view has something
meaningful to see in the mock environment as well.
"""

from __future__ import annotations

